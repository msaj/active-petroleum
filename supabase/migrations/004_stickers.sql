-- Pre-printed QR stickers. Each sticker carries a random code (AP-XXXXXX) and opens /s/<code>.
-- A sticker is linked to a car once, at registration or on the first scan.

create table if not exists public.stickers (
  code text primary key,
  batch text not null,
  seq integer not null,
  created_at timestamptz not null default now()
);
alter table public.stickers enable row level security;
drop policy if exists "stickers staff read" on public.stickers;
create policy "stickers staff read" on public.stickers
  for select to authenticated
  using (public.is_staff());

alter table public.customers add column if not exists sticker_code text references public.stickers (code);
create unique index if not exists customers_sticker_code_idx on public.customers (sticker_code);

